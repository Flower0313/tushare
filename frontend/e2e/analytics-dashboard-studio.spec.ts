import { expect, test } from '@playwright/test'

test('看板在独立工作台拖动图表并保存宽高', async ({ page }) => {
  const board = { id: 7, name: '行情看板', description: '', global_filters: [], query_controls: [], created_at: '2026-10-25T00:00:00Z', updated_at: '2026-10-25T00:00:00Z' }
  const dataset = { id: 4, name: '股票', description: '', source_type: 'TABLE', api_name: 'stock_basic', fields: [], parameters: [] }
  let chart = { id: 9, dashboard_id: 7, dataset_id: 4, title: '股票数量', chart_type: 'number', dimension: null, metric: null, aggregation: 'COUNT', position: 0, grid_span: 1, height_px: 320, filters: [], sort_by: 'metric', sort_desc: true, top_n: 100, date_granularity: null, config: null }
  await page.route('**/api/analytics/**', async (route) => {
    const path = new URL(route.request().url()).pathname.replace('/api/analytics/', '')
    if (path === 'datasets') return route.fulfill({ json: [dataset] })
    if (path === 'dashboards') return route.fulfill({ json: [board] })
    if (path === 'dashboards/7/charts') return route.fulfill({ json: [chart] })
    if (path === 'dashboards/7/charts/9' && route.request().method() === 'PUT') {
      chart = { ...chart, ...route.request().postDataJSON() }
      return route.fulfill({ json: chart })
    }
    if (path === 'dashboards/7/publication') return route.fulfill({ json: { dashboard_id: 7, status: 'DRAFT', version: 0, settings: {} } })
    if (path === 'charts/9/data') return route.fulfill({ json: { columns: ['metric_0'], rows: [{ metric_0: 10 }], points: [{ label: '总计', value: 10 }], truncated: false } })
    if (path === 'datasets/4/query') return route.fulfill({ json: { columns: ['metric_0'], rows: [{ metric_0: 10 }], points: [{ label: '总计', value: 10 }], truncated: false } })
    return route.fulfill({ status: 404, json: { detail: '未配置测试响应' } })
  })
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto('/analytics')
  await page.getByRole('button', { name: '打开行情看板工作台' }).click()
  await expect(page).toHaveURL(/\/analytics\/dashboards\/7\/edit/)
  await expect(page.getByRole('main', { name: '看板工作台' })).toBeVisible()
  await expect(page.locator('.primary-sider')).toHaveCount(0)
  const frame = page.locator('.analytics-chart-frame')
  const before = await frame.boundingBox()
  expect(before).not.toBeNull()
  const grip = page.getByRole('button', { name: '调整股票数量的宽度和高度' })
  const box = await grip.boundingBox()
  expect(box).not.toBeNull()
  await page.mouse.move(box!.x + box!.width / 2, box!.y + box!.height / 2)
  await page.mouse.down()
  await page.mouse.move(box!.x + box!.width / 2 + 180, box!.y + box!.height / 2 + 90, { steps: 6 })
  await page.mouse.up()
  await expect.poll(() => chart.grid_span).toBeGreaterThan(6)
  expect(chart.height_px).toBe(410)
  expect((await frame.boundingBox())!.height).toBeGreaterThan(before!.height)
  await page.reload()
  await expect(page.locator('.analytics-chart-frame')).toHaveCSS('height', '410px')
  await frame.locator('.analytics-chart__header h3').click()
  const editor = page.getByRole('main', { name: '图表设置面板' })
  await expect(editor).toBeVisible()
  expect((await editor.boundingBox())!.x).toBeGreaterThan(800)
  await page.screenshot({ path: 'test-results/analytics-dashboard-chart-editor-1440.png', fullPage: true })
  await page.getByRole('textbox', { name: '图表标题' }).fill('股票总数')
  await page.getByRole('button', { name: '保存图表' }).click()
  await expect(page.getByRole('heading', { name: '股票总数' })).toBeVisible()
  await expect(editor).toHaveCount(0)
  await expect(page).toHaveURL(/\/analytics\/dashboards\/7\/edit/)
  await page.screenshot({ path: 'test-results/analytics-dashboard-studio-1440.png', fullPage: true })
  await page.setViewportSize({ width: 1920, height: 1080 })
  await page.evaluate(() => localStorage.setItem('tushare-platform-theme', 'dark'))
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(page.locator('.analytics-chart-frame')).toBeVisible()
  expect((await page.locator('.analytics-chart-grid').boundingBox())!.width).toBeGreaterThan(1700)
  await page.locator('.analytics-chart__header h3').click()
  await expect(editor).toBeVisible()
  await page.screenshot({ path: 'test-results/analytics-dashboard-chart-editor-1920-dark.png', fullPage: true })
  await editor.getByRole('button', { name: /取\s*消/ }).click()
  await page.screenshot({ path: 'test-results/analytics-dashboard-studio-1920-dark.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(frame).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
  await frame.locator('.analytics-chart__header h3').click()
  await expect(editor).toBeVisible()
  expect((await page.getByRole('dialog', { name: '图表设置' }).boundingBox())!.width).toBeLessThanOrEqual(390)
})
